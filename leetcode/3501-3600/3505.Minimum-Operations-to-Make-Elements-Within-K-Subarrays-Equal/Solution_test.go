package Solution

import (
	"reflect"
	"strconv"
	"testing"
)

func TestSolution(t *testing.T) {
	//	测试用例
	cases := []struct {
		name   string
		inputs []int
		x, k   int
		expect int64
	}{
		{"TestCase1", []int{5, -2, 1, 3, 7, 3, 6, 4, -1}, 3, 2, 8},
		{"TestCase2", []int{9, -2, -2, -2, 1, 5}, 2, 2, 3},
	}

	//	开始测试
	for i, c := range cases {
		t.Run(c.name+" "+strconv.Itoa(i), func(t *testing.T) {
			got := Solution(c.inputs, c.x, c.k)
			if !reflect.DeepEqual(got, c.expect) {
				t.Fatalf("expected: %v, but got: %v, with inputs: %v %v %v",
					c.expect, got, c.inputs, c.x, c.k)
			}
		})
	}
}

